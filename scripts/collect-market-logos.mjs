// Download reviewed public logo URLs. Run with network access after updating sources.json.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const directory = new URL('../public/assets/markets/', import.meta.url);
await mkdir(directory, { recursive: true });
const sources = JSON.parse(await readFile(new URL('sources.json', directory), 'utf8'));
let next = 0;
const missing = [];
await Promise.all(Array.from({ length: 8 }, async () => {
  while (next < sources.length) {
    const entry = sources[next++];
    if (entry.file && /^[a-f0-9]{20}\.(png|jpg|webp|svg)$/.test(entry.file)) {
      try { await readFile(new URL(entry.file, directory)); continue; }
      catch { delete entry.file; delete entry.source; }
    }
    for (const url of entry.candidates) {
      try {
        const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
        if (!response.ok) continue;
        const bytes = Buffer.from(await response.arrayBuffer());
        if (bytes.length < 100 || bytes.length > 2_000_000) continue;
        let extension;
        if (bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10]))) extension = 'png';
        else if (bytes[0] === 255 && bytes[1] === 216 && bytes[2] === 255) extension = 'jpg';
        else if (bytes.toString('ascii', 0, 4) === 'RIFF' && bytes.toString('ascii', 8, 12) === 'WEBP') extension = 'webp';
        else if (/<svg[\s>]/i.test(bytes.toString('utf8')) && !/<(?:script|foreignObject)\b|\bon\w+\s*=|(?:href|url\()\s*=?\s*["']?\s*(?:https?:|\/\/|javascript:)/i.test(bytes.toString('utf8'))) extension = 'svg';
        if (!extension) continue;
        const file = `${createHash('sha256').update(entry.symbol).digest('hex').slice(0, 20)}.${extension}`;
        await writeFile(new URL(file, directory), bytes);
        entry.file = file;
        entry.source = url;
        break;
      } catch { /* Try the next reviewed source; retain the text fallback if unavailable. */ }
    }
    if (!entry.file) missing.push(entry.symbol);
  }
}));
sources.sort((a, b) => a.symbol.localeCompare(b.symbol));
await writeFile(new URL('sources.json', directory), JSON.stringify(sources, null, 2) + '\n');
const logos = Object.fromEntries(sources.filter(e => e.file).map(e => [e.symbol, `/assets/markets/${e.file}`]));
await writeFile(new URL('../public/market-logos.js', import.meta.url), `// Generated by scripts/collect-market-logos.mjs. Sources: assets/markets/sources.json\nexport const marketLogos = ${JSON.stringify(logos, null, 2)};\n`);
console.log(JSON.stringify({ downloaded: Object.keys(logos).length, total: sources.length, missing }));
